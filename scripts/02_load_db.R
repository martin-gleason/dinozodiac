# 02: Load data/processed/*.csv into PostgreSQL (overwrites the tables).
# Run scripts/01_parse_archive.R first, and create .env from .env.example.
library(DBI)
library(readr)
library(here)

source(here("R", "db.R"))

read_table <- function(name) {
  read_csv(here("data", "processed", paste0(name, ".csv")), show_col_types = FALSE)
}

con <- dz_connect()
# on.exit() doesn't fire at the top level of a script, so disconnect explicitly.

# Make `id` the primary key and let Postgres number new rows after the max id.
# (GENERATED ... AS IDENTITY is the modern replacement for hand-made sequences.)
add_identity_key <- function(con, table, id) {
  next_id <- dbGetQuery(con, sprintf("SELECT COALESCE(MAX(%s), 0) + 1 AS n FROM %s",
                                     id, table))$n
  dbExecute(con, sprintf("ALTER TABLE %s ADD PRIMARY KEY (%s)", table, id))
  dbExecute(con, sprintf(
    "ALTER TABLE %s ALTER COLUMN %s ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %d)",
    table, id, as.integer(next_id)
  ))
}

dbWithTransaction(con, {
  # scopes references the other two, so drop it first.
  dbExecute(con, "DROP TABLE IF EXISTS scopes, signs, sources")

  dbWriteTable(con, "signs",   read_table("signs"))
  dbWriteTable(con, "sources", read_table("sources"))
  dbWriteTable(con, "scopes",  read_table("scopes"))

  add_identity_key(con, "signs",   "sign_id")
  add_identity_key(con, "sources", "source_id")
  add_identity_key(con, "scopes",  "scope_id")

  dbExecute(con, "ALTER TABLE scopes ADD FOREIGN KEY (sign_id)   REFERENCES signs")
  dbExecute(con, "ALTER TABLE scopes ADD FOREIGN KEY (source_id) REFERENCES sources")
  dbExecute(con, "ALTER TABLE scopes ADD UNIQUE (date, source_id, sign_id)")
})

message("Loaded: ", toString(dbListTables(con)))
dbDisconnect(con)
